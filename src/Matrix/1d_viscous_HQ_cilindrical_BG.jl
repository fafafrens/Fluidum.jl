# the convention here are α, nur; the background (T, ur, dtT, drT, drur, dtur) = background_fields(tau, r) is prescribed
# Fick closure:       Nabla.(n u + nu) = 0, tau_n Delta D nu + nu + kappa Delta grad(alpha) = 0
# consistent closure: Nabla.(n u + nu) = 0, (D_s/T) Delta^r_l Nabla_m T_Q^{ml} + nu^r = 0, P0 = nT

"""
    matrix1d_visc_HQ_BG!(; background_fields, dmn_eps = 1e-6, α_max = 200.0)
Charm first moment (α, ν^r) on a prescribed 1+1D cylindrical background, Fick closure.
"""
function matrix1d_visc_HQ_BG!(;dmn_eps=1e-6, background_fields, α_max=200.0)
    (A_i, Source, ϕ, tau, X, params) -> matrix1d_visc_HQ_BG!(A_i, Source, ϕ, tau, X, params;dmn_eps=dmn_eps,background_fields=background_fields, α_max=α_max)
end


function matrix1d_visc_HQ_BG!(A_i,Source,ϕ,tau,X,params;dmn_eps=1e-6,background_fields= nothing, α_max=200.0)

    T,ur,dtT,drT,drur,dtur = background_fields(tau,X[1])

    α_safe = clamp(ϕ[1], -α_max, α_max)

    thermo = thermodynamic(T,α_safe,params.eos.hadron_list)
    n=thermo.pressure
    dn_dT, dn_dmu = thermo.pressure_derivative
    dn_dmu+= dmn_eps

    κ = diffusion_hadron(T,α_safe,params.eos,params.diffusion) #diffusion coefficient for hadrons
    tauDiffusion=τ_diffusion_hadron(T,α_safe,params.eos,params.diffusion)

    (At,Ax, source)=one_d_viscous_matrix_fugacity_BG_only(ϕ,tau,X[1],ur,dtT,drT,drur,dtur,n,dn_dmu,dn_dT,tauDiffusion,κ)


    Ainv= inv(At)


    A_mul_B!(A_i[1], Ainv,Ax)


    jgemvavx!(Source, Ainv,source)

    end



function one_d_viscous_matrix_fugacity_BG_only(u,tau,r,ur,dtT,drT,drur,dtur,n,dn_dmu,dn_dT,tauDiffusion,κ)
    # every row multiplied by u^tau^3 r tau
    At=SMatrix{2,2}(((1  .+ ur .^2) .^2 .*r .*tau .*dn_dmu,

κ .*ur .*(1  .+ ur .^2) .^2 .*r .*tau,

ur .*(1  .+ ur .^2) .*r .*tau,

(1  .+ ur .^2) .^2 .*tauDiffusion .*r .*tau))

    Ax=SMatrix{2,2}(
        (ur .*(1  .+ ur .^2) .^1.5 .*r .*tau .*dn_dmu,

  κ .*(1  .+ ur .^2) .^2.5  .*r .*tau,

(1  .+ ur .^2) .^1.5 .*r .*tau,

ur .*(1  .+ ur .^2) .^1.5 .*tauDiffusion .*r .*tau)
    )

    source=SVector{2}(
    (u[2] .*(sqrt.(1  .+ ur .^2) .*tau  .+ ur .^2 .*sqrt.(1  .+ ur .^2) .*tau  .+ r .*(ur  .+ ur .^3  .+ dtur .*tau))  .+ (1  .+ ur .^2) .*n .*(ur .*sqrt.(1  .+ ur .^2) .*tau  .+ r .*(1  .+ ur .^2  .+ dtur .*ur .*tau  .+ drur .*sqrt.(1  .+ ur .^2) .*tau))  .+ (1  .+ ur .^2) .*(dtT  .+ dtT .*ur .^2  .+ drT .*ur .*sqrt.(1  .+ ur .^2)) .*r .*tau .*dn_dT,

(sqrt.(1  .+ ur .^2)  .- ur .*(dtur .*tauDiffusion  .+ dtur .*ur .^2 .*tauDiffusion  .+ ur .*sqrt.(1  .+ ur .^2) .*( .-1  .+ drur .*tauDiffusion))) .*r .*u[2] .*tau)
    )

    return (At,Ax, source)
end


"""
    matrix1d_visc_HQ_BG_consistent!(; background_fields, dmn_eps = 1e-6, α_max = 200.0)
Charm first moment (α, ν^r) on a prescribed 1+1D cylindrical background, consistent closure:
at rest the current relaxes to -κ∇α - (D_s/T)(n + T ∂_T n)∇T.
"""
function matrix1d_visc_HQ_BG_consistent!(; dmn_eps = 1e-6, background_fields, α_max = 200.0)
    (A_i, Source, ϕ, tau, X, params) -> matrix1d_visc_HQ_BG_consistent!(A_i, Source, ϕ, tau, X, params;
        dmn_eps = dmn_eps, background_fields = background_fields, α_max = α_max)
end

function matrix1d_visc_HQ_BG_consistent!(A_i, Source, ϕ, tau, X, params;
        dmn_eps = 1e-6, background_fields = nothing, α_max = 200.0)

    T, ur, dtT, drT, drur, dtur = background_fields(tau, X[1])

    ch = charm_eos(T, clamp(ϕ[1], -α_max, α_max), params.eos.hadron_list)
    Ds = DsT(params.diffusion, T) / T / fmGeV

    # dn/dα + dmn_eps keeps inv(At) regular where n -> 0; it enters kappa = D_s dn/dα too
    (At, Ax, source) = one_d_HQ_BG_consistent_matrix(ϕ, tau, X[1], T, ur, dtT, drT, dtur, drur,
                                                     ch.n, ch.dndT, ch.dnda + dmn_eps, ch.h, ch.dhdT, Ds)

    Ainv = inv(At)
    A_mul_B!(A_i[1], Ainv, Ax)
    jgemvavx!(Source, Ainv, source)
end


